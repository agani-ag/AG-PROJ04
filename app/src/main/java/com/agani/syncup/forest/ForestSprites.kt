/** Decoded sprites, least recently used dropped first. Safe from any thread; a miss decodes on the caller's thread. */
internal object SpriteImages {
    private const val MAX_BYTES = 37 * 1024 * 1024 // every sprite decoded fits

    private val cache = object : LruCache<Sprite, ImageBitmap>(MAX_BYTES) {
        override fun sizeOf(key: Sprite, value: ImageBitmap) = value.width * value.height * 4
    }

    /** The sprite's picture at its own pixel size (nodpi, never rescaled). Blocking on a miss: one small WebP decode. */
    fun get(context: Context, sprite: Sprite): ImageBitmap {
        cache.get(sprite)?.let { return it }
        val bmp = checkNotNull(BitmapFactory.decodeResource(context.resources, sprite.res, BitmapFactory.Options().apply { inScaled = false })) {
            "sprite ${sprite.name} did not decode"
        }
        bmp.setHasMipMap(true) // smoother when drawn much smaller than its size
        val img = bmp.asImageBitmap()
        cache.put(sprite, img)
        return img
    }

    fun clear() = cache.evictAll()
}

/**
 * Draws [sprite]'s picture [img] so the symbol's base point, (50, 96) or (100, 226) for a tree, lands on
 * ([x], [baseY]). [w] is the on-screen width of the standard box (100 units, 200 for a tree); art outside
 * that box keeps the same scale, so a sprite with a bigger box comes out proportionally bigger.
 * [flip] mirrors around [x] (an animal then faces left).
 */
internal fun DrawScope.drawSprite(
    img: ImageBitmap,
    sprite: Sprite,
    x: Float,
    baseY: Float,
    w: Float,
    flip: Boolean = false,
    alpha: Float = 1f,
    colorFilter: ColorFilter? = null,
) {
    if (w <= 0f || img.width <= 0 || img.height <= 0) return
    val k = w / (if (sprite.tree) 200f else 100f) // px per unit
    val left = x + (sprite.x0 - (if (sprite.tree) 100f else 50f)) * k
    val top = baseY + (sprite.y0 - (if (sprite.tree) 226f else 96f)) * k
    val size = IntSize(img.width, img.height)
    withTransform({
        if (flip) scale(-1f, 1f, Offset(x, baseY))
        translate(left, top)
        scale((sprite.x1 - sprite.x0) * k / img.width, (sprite.y1 - sprite.y0) * k / img.height, Offset.Zero)
    }) {
        drawImage(img, IntOffset.Zero, size, IntOffset.Zero, size, alpha = alpha, colorFilter = colorFilter, filterQuality = FilterQuality.Medium)
    }
}
